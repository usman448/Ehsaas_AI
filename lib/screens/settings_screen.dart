import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/material.dart';
import 'package:image_picker/image_picker.dart';
import '../app.dart';
import '../services/auth_service.dart';
import '../services/firestore_service.dart';
import '../widgets/common.dart';

class SettingsScreen extends StatelessWidget {
  const SettingsScreen({super.key});

  void _info(BuildContext c, String title, String body) =>
      showDialog(context: c, builder: (d) => AlertDialog(title: Text(title), content: Text(body), actions: [TextButton(onPressed: () => Navigator.pop(d), child: const Text('OK'))]));

  Future<void> _pick(ImageSource src) async {
    final x = await ImagePicker().pickImage(source: src, maxWidth: 512, maxHeight: 512, imageQuality: 80);
    if (x != null) await appState.setAvatar(await x.readAsBytes());
  }

  void _photoMenu(BuildContext context) => showModalBottomSheet(
        context: context,
        builder: (d) => SafeArea(
          child: Column(mainAxisSize: MainAxisSize.min, children: [
            ListTile(leading: const Icon(Icons.photo_library_outlined), title: const Text('Choose from gallery'), onTap: () { Navigator.pop(d); _pick(ImageSource.gallery); }),
            ListTile(leading: const Icon(Icons.photo_camera_outlined), title: const Text('Take a photo'), onTap: () { Navigator.pop(d); _pick(ImageSource.camera); }),
            if (appState.avatar != null) ListTile(leading: const Icon(Icons.delete_outline, color: Colors.red), title: const Text('Remove photo'), onTap: () { Navigator.pop(d); appState.setAvatar(null); }),
          ]),
        ),
      );

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    final isGuest = appState.guest || !appState.firebaseReady || FirebaseAuth.instance.currentUser == null;
    return SafeArea(
      child: ListView(padding: const EdgeInsets.fromLTRB(20, 16, 20, 20), children: [
        Text(tr('Settings', 'ترتیبات'), style: const TextStyle(fontSize: 22, fontWeight: FontWeight.w800)),
        const SizedBox(height: 14),
        SoftCard(
          child: isGuest
              ? const Row(children: [AppLogo(size: 52), SizedBox(width: 14), Expanded(child: Text('Guest mode\nLogin to add a profile picture', style: TextStyle(fontWeight: FontWeight.w600)))])
              : FutureBuilder<Map<String, dynamic>?>(
                  future: AuthService().profile(),
                  builder: (_, s) {
                    final name = '${s.data?['name'] ?? FirebaseAuth.instance.currentUser?.displayName ?? ''}';
                    return Row(children: [
                      Stack(children: [
                        UserAvatar(bytes: appState.avatar, name: name, size: 68, onTap: () => _photoMenu(context)),
                        Positioned(right: 0, bottom: 0, child: GestureDetector(onTap: () => _photoMenu(context), child: const CircleAvatar(radius: 12, backgroundColor: kPurple, child: Icon(Icons.camera_alt, size: 13, color: Colors.white)))),
                      ]),
                      const SizedBox(width: 14),
                      Expanded(child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                        Text(name, style: const TextStyle(fontWeight: FontWeight.w800, fontSize: 16)),
                        Text('${s.data?['role'] ?? ''}', style: const TextStyle(color: kPurple, fontWeight: FontWeight.w600, fontSize: 12)),
                        Text(FirebaseAuth.instance.currentUser?.email ?? '', style: TextStyle(color: cs.onSurfaceVariant, fontSize: 12)),
                      ])),
                    ]);
                  },
                ),
        ),
        SoftCard(
          padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 4),
          child: Column(children: [
            SwitchListTile(contentPadding: EdgeInsets.zero, title: const Text('Dark mode'), subtitle: Text(appState.mode == ThemeMode.dark ? 'Dark' : 'Light'), value: appState.mode == ThemeMode.dark, onChanged: appState.setDark),
            ListTile(
              contentPadding: EdgeInsets.zero,
              title: const Text('Language'),
              trailing: SegmentedButton<String>(
                showSelectedIcon: false,
                segments: const [ButtonSegment(value: 'en', label: Text('English')), ButtonSegment(value: 'ur', label: Text('اردو'))],
                selected: {appState.lang},
                onSelectionChanged: (s) => appState.setLang(s.first),
              ),
            ),
            ListTile(contentPadding: EdgeInsets.zero, title: const Text('About Ehsaas AI'), trailing: const Icon(Icons.chevron_right), onTap: () => _info(context, 'About Ehsaas AI', 'Ehsaas AI shows how emotions in Urdu text can be presented.\n\nIMPORTANT: emotion results in this version are DEMO results from a mock service. They are not generated by a trained AI model.')),
            ListTile(contentPadding: EdgeInsets.zero, title: const Text('Privacy'), trailing: const Icon(Icons.chevron_right), onTap: () => _info(context, 'Privacy', 'Your sentences are only stored if you tap Save Result while logged in. Saved items live in your own private Firestore area and only you can read them. Your profile picture stays on this device. Guests store nothing.')),
          ]),
        ),
        if (!isGuest)
          OutlinedButton.icon(
            style: OutlinedButton.styleFrom(foregroundColor: Colors.red, padding: const EdgeInsets.symmetric(vertical: 15)),
            icon: const Icon(Icons.delete_outline),
            label: const Text('Clear analysis history'),
            onPressed: () async {
              final ok = await showDialog<bool>(context: context, builder: (d) => AlertDialog(title: const Text('Clear history?'), content: const Text('All saved analyses will be deleted.'), actions: [TextButton(onPressed: () => Navigator.pop(d, false), child: const Text('Cancel')), TextButton(onPressed: () => Navigator.pop(d, true), child: const Text('Clear'))]));
              if (ok == true) await FirestoreService().clear();
            },
          ),
        const SizedBox(height: 10),
        OutlinedButton.icon(
          style: OutlinedButton.styleFrom(padding: const EdgeInsets.symmetric(vertical: 15)),
          icon: Icon(isGuest ? Icons.login : Icons.logout),
          label: Text(isGuest ? 'Login / Sign Up' : 'Logout'),
          onPressed: () async {
            if (!isGuest) await AuthService().logout();
            appState.setGuest(false);
          },
        ),
        const SizedBox(height: 16),
        Center(child: Text('Version 1.0.0 · Demo build', style: TextStyle(color: cs.onSurfaceVariant, fontSize: 12))),
      ]),
    );
  }
}
